"""Regenerate normalized 81-wavelength illuminants from the Python reference."""
from pathlib import Path
import json,colour
from spektrafilm.model.illuminants import standard_illuminant
rows=[]
for name in list(colour.SDS_ILLUMINANTS)+['T','K75P','TH-KG3','TH-KG3-L']:
 rows.append('('+json.dumps(name)+','+repr(standard_illuminant(name).tolist())+'),')
Path('crates/spektrafilm-math/src/illuminant_registry.rs').write_text('// Generated by scripts/reference/generate_illuminants.py.\npub static ILLUMINANTS: &[(&str,[f64;81])]= &[\n'+ '\n'.join(rows)+'\n];\n')
